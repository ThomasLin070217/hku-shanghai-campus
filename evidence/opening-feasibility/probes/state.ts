import {writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {CampusGame} from '../../../src/exploration/game.ts';
import {createNavigation} from '../../../src/exploration/navigation.ts';
import {BUILDINGS,SITE} from '../../../src/model/campusParameters.ts';
import {captureSave,parseSave,restoreSave,DEFAULT_SETTINGS} from '../../../src/gameplay/save.ts';
import {validateAction} from '../../../src/agent/protocol.ts';
const g=new CampusGame(createNavigation(BUILDINGS,SITE),BUILDINGS);
const results:any[]=[];
let save=captureSave(g,DEFAULT_SETTINGS);
assert.ok(parseSave(save));
results.push({check:'existing-default-save-accepted',pass:true});
const empty=structuredClone(save);empty.slots=Array(36).fill(null);
assert.equal(parseSave(empty),null);
results.push({check:'pre-laptop-save-currently-rejected',confirmed:true});
g.inventory.move(9,0);g.inventory.select(0);
g.enableAI();assert.ok(g.acquireControl('offline-probe').ok);
const a={commandId:'computer-probe',controlEpoch:g.epoch,durationMs:100,computer:'tasks' as const};
assert.ok(g.act(a,1000).ok);g.step(1/120,1010);
assert.equal(g.last?.operation?.code,'page_ready');assert.equal(g.panel,null);assert.equal(g.paused,false);assert.equal(g.owner,'offline-probe');
results.push({check:'RPC-computer-only-survey-operation-no-modal-or-takeover',confirmed:true});
assert.equal(validateAction({...a,computer:undefined,interact:'opening.staff'}),false);
assert.equal(validateAction({...a,computer:undefined,interact:'opening-staff'}),true);
results.push({check:'RPC-interact-hyphen-id-accepted-dot-id-rejected',confirmed:true});
const epoch=g.epoch;g.openPanel('computer');assert.equal(g.owner,null);assert.equal(g.armed,false);assert.equal(g.paused,true);assert.ok(g.epoch>epoch);
assert.equal(g.act({...a,commandId:'stale-after-panel'},1020).ok,false);
results.push({check:'existing-modal-pauses-and-invalidates-control',pass:true});
save=captureSave(g,DEFAULT_SETTINGS);save.position=[BUILDINGS[0].x,0,BUILDINGS[0].z];
const restored=restoreSave(g,save);assert.equal(restored.recoveredPosition,true);assert.equal(g.inventory.equipped?.itemId,'macbook-air-13-silver');
results.push({check:'existing-unsafe-position-recovery-retains-inventory',pass:true,spawn:g.body.position.toArray()});
g.body.world.dispose();

const h=new CampusGame(createNavigation(BUILDINGS,SITE),BUILDINGS);
const duplicated=captureSave(h,DEFAULT_SETTINGS);duplicated.slots[0]={itemId:'macbook-air-13-silver',instanceId:'second-distinct-instance',count:1};
assert.ok(parseSave(duplicated));
results.push({check:'existing-parser-allows-two-laptops-if-instance-ids-differ',confirmed:true});
const withStory={...captureSave(h,DEFAULT_SETTINGS),opening:{stage:'bus',flags:['invitation_read']}};
assert.equal('opening' in parseSave(withStory)!,false);
results.push({check:'existing-parser-strips-unrecognized-opening-field',confirmed:true});
h.body.world.dispose();

const report={scope:'Offline baseline behavior diagnostics, not new opening tests',results};
writeFileSync(new URL('../state-results.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
