"""Import the WorkBuddy runtime WAV delivery, excluding raw archives/evidence.

Usage: python3 scripts/audio/import-pack.py /absolute/path/to/audio-out
"""
import hashlib
import json
from pathlib import Path
import shutil
import sys
import wave
import zipfile

root = Path(__file__).resolve().parents[2]
source = Path(sys.argv[1]).resolve()
target = root / 'assets/audio/story'
target.mkdir(parents=True, exist_ok=True)
config = json.loads((source / 'audio-triggers.json').read_text())
entries = [(c['id'], c['file']) for c in config['cues']]
entries += [('mus_' + key, value['file']) for key, value in config['musicLayers'].items()]
report = []
urls = ['// Generated by scripts/audio/import-pack.py. Edit the delivery config, then re-import.',
        'export const STORY_AUDIO_URLS:Record<string,URL>={']
for name, relative in entries:
    src = source / relative
    with wave.open(str(src), 'rb') as wav:
        assert wav.getsampwidth() == 2 and wav.getnchannels() in (1, 2)
        report.append(dict(id=name, file=relative, sampleRate=wav.getframerate(),
                           channels=wav.getnchannels(), frames=wav.getnframes(),
                           sha256=hashlib.sha256(src.read_bytes()).hexdigest()))
    dst = target / relative
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    urls.append(f" {name!r}:new URL('../../assets/audio/story/{relative}',import.meta.url),")
with zipfile.ZipFile(source / 'cc0/raw/oga_door_closes_starninjas.zip') as archive:
    relative = 'cc0/processed/bus_door.ogg'
    data = archive.read('door.1.ogg')
    (target / relative).write_bytes(data)
    report.append(dict(id='bus_door', file=relative, sha256=hashlib.sha256(data).hexdigest()))
    urls.append(f" 'bus_door':new URL('../../assets/audio/story/{relative}',import.meta.url),")
urls.append('};\n')
(root / 'src/gameplay/storyAudioAssets.ts').write_text('\n'.join(urls))
shutil.copy2(source / 'audio-triggers.json', target / 'audio-triggers.json')
shutil.copy2(source / 'cc0/MANIFEST.md', target / 'SOURCES.md')
(target / 'IMPORT.json').write_text(json.dumps(report, indent=2) + '\n')
docs = root / 'docs/audio/source'
docs.mkdir(parents=True, exist_ok=True)
for file in (source / 'docs').iterdir():
    if file.is_file():
        shutil.copy2(file, docs / file.name)
for file in (source / 'scripts').glob('*.py'):
    code = file.read_text().replace('Path(__file__).parent.parent',
        "Path(__file__).resolve().parents[2] / 'assets' / 'audio' / 'story'")
    code = code.replace("(ROOT / 'docs' / 'QA-Report.json')",
        "(Path(__file__).resolve().parents[2] / 'docs/audio/QA-Assets.json')")
    code = code.replace('Codex must resample on import (own audio.ts expects single rate)',
        'decodeAudioData resamples to the browser context; see browser verification report')
    (root / 'scripts/audio' / file.name).write_text(code)
print(f'Imported {len(entries)} WAVs + 1 CC0 door OGG; raw archives stay outside the runtime project.')
